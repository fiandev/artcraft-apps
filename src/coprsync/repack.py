"""Repackage a prebuilt upstream RPM as an SRPM that Copr can build.

Public Copr rejects direct binary uploads, so the only supported way in is an
SRPM. The generated spec carries the upstream RPM as Source0, unpacks it in
%prep and installs the existing payload verbatim: no compiler, no rebuild from
source. One SRPM is produced per upstream architecture, because the payload has
to match the chroot that builds it.
"""

from __future__ import annotations

import shutil
import subprocess
from pathlib import Path
from string import Template

from .errors import RpmError
from .rpmmeta import RpmMeta

SPEC_TEMPLATE = Template(
    """\
# Generated by coprsync. Repackages the prebuilt upstream RPM so Copr can
# publish it for each target chroot. Do not edit by hand.
%global __os_install_post %{nil}
%global debug_package %{nil}

Name:           ${name}
${epoch_line}Version:        ${version}
Release:        ${release}
Summary:        ${summary}
License:        ${license}
${url_line}${vendor_line}${group_line}Source0:        ${source}
AutoReqProv:    no
BuildRequires:  cpio
BuildRequires:  rpm
${requires_lines}
%description
${description}

%prep
rm -rf %{_builddir}/payload
mkdir -p %{_builddir}/payload
cd %{_builddir}/payload
rpm2cpio %{SOURCE0} | cpio -idmu --quiet

%install
mkdir -p %{buildroot}
cp -a %{_builddir}/payload/. %{buildroot}/

%files
${files}
"""
)


def generate_spec(meta: RpmMeta, source_name: str) -> str:
    return SPEC_TEMPLATE.substitute(
        name=meta.name,
        epoch_line=f"Epoch:          {meta.epoch}\n" if meta.epoch else "",
        version=meta.version,
        release=meta.release,
        summary=_escape(meta.summary),
        license=meta.license,
        url_line=f"URL:            {meta.url}\n" if meta.url else "",
        vendor_line=f"Vendor:         {_escape(meta.vendor)}\n" if meta.vendor else "",
        group_line=f"Group:          {meta.group}\n" if meta.group else "",
        source=source_name,
        requires_lines="".join(f"Requires:       {req}\n" for req in meta.requires),
        description=_escape(meta.description),
        files="".join(f"{_escape(path)}\n" for path in meta.files),
    )


def build_srpm(rpm_path: Path, meta: RpmMeta, workdir: Path) -> Path:
    """Build a source RPM wrapping `rpm_path`. Returns the .src.rpm path."""
    topdir = workdir / "rpmbuild"
    for sub in ("SPECS", "SOURCES", "BUILD", "BUILDROOT", "RPMS", "SRPMS"):
        (topdir / sub).mkdir(parents=True, exist_ok=True)

    source_name = rpm_path.name
    shutil.copy2(rpm_path, topdir / "SOURCES" / source_name)
    spec_path = topdir / "SPECS" / f"{_spec_stem(meta)}.spec"
    spec_path.write_text(generate_spec(meta, source_name))

    argv = [
        "rpmbuild",
        "-bs",
        "--define",
        f"_topdir {topdir}",
        "--define",
        f"_srcrpmdir {topdir / 'SRPMS'}",
        str(spec_path),
    ]
    try:
        result = subprocess.run(argv, capture_output=True, text=True, check=False)
    except FileNotFoundError as exc:
        raise RpmError("rpmbuild is not installed; install the rpm-build package") from exc
    if result.returncode != 0:
        raise RpmError(f"rpmbuild -bs failed for {meta.name}:\n{result.stderr.strip()}")

    built = sorted((topdir / "SRPMS").glob("*.src.rpm"))
    if not built:
        raise RpmError(f"rpmbuild reported success but produced no SRPM for {meta.name}")
    return built[-1]


def _spec_stem(meta: RpmMeta) -> str:
    return "".join(ch if ch.isalnum() or ch in "-._+" else "_" for ch in meta.name)


def _escape(text: str) -> str:
    """Neutralise anything rpm would read as a macro."""
    return text.replace("%", "%%")
